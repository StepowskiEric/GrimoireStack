/**
 * build-ai-catalog.mjs — Generate the skill catalog for the AI recommendation function.
 *
 * Reads schoolsRegistry.js and outputs a compact JS module at
 * functions/api/skill-catalog.js that the Pages Function imports.
 *
 * Run as part of the build pipeline (or manually after registry changes).
 */

import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REGISTRY_PATH = resolve(__dirname, '../src/data/schoolsRegistry.js');
const OUTPUT_PATH = resolve(__dirname, '../functions/api/skill-catalog.js');

const registryContent = readFileSync(REGISTRY_PATH, 'utf-8');

// Extract the schools array from the JS module.
// The file is: comments + `const schools = [` + data + `];` + `export default schools;`
// We need to extract just the array literal.
const startMarker = 'const schools = [';
const startIdx = registryContent.indexOf(startMarker);
if (startIdx === -1) throw new Error('Could not find schools array in registry');
const arrayStart = startIdx + startMarker.length - 1; // point at '['
const endIdx = registryContent.lastIndexOf('];');
if (endIdx === -1) throw new Error('Could not find end of schools array');
const arrayContent = registryContent.slice(arrayStart, endIdx + 1); // "[...]"
const schools = eval(`(${arrayContent})`);
// Build condensed catalog entries
const entries = [];
for (const school of schools) {
  for (const spell of school.spells) {
    // Keep effects long enough for local token-overlap matching to work well.
    let effect = spell.effect || '';
    if (effect.length > 500) {
      effect = effect.substring(0, 497) + '...';
    }
    entries.push({
      skill: spell.skill,
      name: spell.name,
      school: school.real,
      schoolName: school.name,
      status: spell.status || '',
      effect,
    });
  }
}

// Generate the output module
const output = `// AUTO-GENERATED by scripts/build-ai-catalog.mjs — DO NOT EDIT
// Run \`node scripts/build-ai-catalog.mjs\` after registry changes.

export const SKILL_CATALOG = ${JSON.stringify(entries, null, 2)};
`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, output, 'utf-8');

console.log(`Generated skill catalog: ${entries.length} entries → ${OUTPUT_PATH}`);
console.log(`Estimated prompt tokens: ~${Math.round(JSON.stringify(entries).length / 4)}`);
