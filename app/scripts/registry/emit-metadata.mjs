/**
 * emit-metadata.mjs — Build the EXPLICIT spell-metadata map.
 *
 * Data-only. Helper functions live in app/src/data/changeFeed.js.
 *
 * Inputs: an array of parsed skills (with skill id and last-updated
 * from frontmatter or file mtime, plus optional note).
 *
 * Returns: a JSON-serializable map of skill-id -> { lastUpdated, note? }.
 *
 * Pure function — no file I/O. The caller writes the result.
 */

export function buildExplicit(skills) {
  const explicit = {};
  for (const s of skills) {
    const entry = { lastUpdated: s.lastUpdated };
    if (s.note) entry.note = s.note;
    explicit[s.skill] = entry;
  }
  return explicit;
}

export function renderMetadataSource(explicit) {
  const sortedKeys = Object.keys(explicit).sort();
  const lines = [
    '/**',
    ' * AUTO-GENERATED by scripts/registry/index.mjs — DO NOT EDIT',
    ' *',
    ' * The EXPLICIT map is generated from the filesystem (file mtime +',
    ' * optional `note` / `last-updated` from SKILL.md frontmatter).',
    ' *',
    ' * Helper functions live in ./changeFeed.js.',
    ' */',
    '',
    'export const EXPLICIT = {',
  ];
  for (const key of sortedKeys) {
    const entry = explicit[key];
    const fields = [`lastUpdated: '${entry.lastUpdated}'`];
    if (entry.note) fields.push(`note: ${JSON.stringify(entry.note)}`);
    lines.push(`  '${key}': { ${fields.join(', ')} },`);
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}
